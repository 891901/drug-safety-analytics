"""Drug co-occurrence analysis over the real FDA FAERS 2026 extracts.

Reuses the existing ingestion and preprocessing modules to read the cleaned
DEMO and DRUG tables for the configured quarters and mines every drug pair that
was reported together in the same FAERS report.

What is produced
----------------
1. the drugs reported together in the same report (report x drug incidence);
2. the frequency of every drug pair;
3. the top 20 most frequent drug combinations;
4. support, confidence and lift for those pairs;
5. a Q1 vs Q2 comparison (each quarter mined separately);
6. frequently co-reported drug groups (three-drug combinations).

Design decisions
----------------
* **Reports are identified by ``(quarter, PRIMARYID)``.** ``PRIMARYID`` is the
  FAERS report identifier and ``quarter`` is the provenance column added at
  ingestion, so a pair is only ever formed *inside one report of one quarter*.
* **Duplicate drug names inside a report are removed before pairing.** Every
  aggregation works on the *distinct* ``(quarter, PRIMARYID, DRUGNAME_STD)``
  projection, so a report that repeats a drug name cannot create a self-pair.
* **Canonical ordering: ``drug_a < drug_b``.** The pair is generated by an
  inner self-join of the report x drug projection on ``(quarter, PRIMARYID)``
  and filtered to ``drug_a < drug_b``. That single guard removes self-pairs
  *and* the reversed duplicate ``B+A`` at once, so each unordered pair is
  counted exactly once per report.
* **No Cartesian join.** The self-join is an equi-join on the report key
  ``(quarter, PRIMARYID)``; the only other joins are broadcast look-ups of the
  per-drug report counts needed for confidence and lift.
* **Q1 and Q2 are mined separately** and are never merged into one count.
* **The counts describe reporting, not risk.** Two drugs appearing in the same
  report says nothing about interaction, causality or comparative safety.

Environment constraints honoured: PySpark DataFrames only, no pandas, no
PyArrow, no UDFs, no Parquet. Only small aggregated result sets are collected
to the driver and written with the Python standard library.

Usage::

    python -m src.analytics.drug_cooccurrence
    python -m src.analytics.drug_cooccurrence --quarters 2026_Q1
"""

