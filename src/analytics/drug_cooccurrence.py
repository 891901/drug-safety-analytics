def render_report(
    results: CooccurrenceResults,
    *,
    generated_at: Optional[datetime] = None,
) -> str:
    """Render the co-occurrence report as plain text."""
    stamp = (generated_at or datetime.now()).strftime("%Y-%m-%d %H:%M:%S")
    thresholds = results.thresholds

    lines: List[str] = [
        "=" * 90,
        "FAERS DRUG CO-OCCURRENCE ANALYSIS REPORT",
        f"Generated : {stamp}",
        f"Quarters  : {', '.join(results.quarters)}",
        "Engine    : PySpark DataFrame API only (no pandas, no PyArrow, no UDFs)",
        "Source    : real FAERS 2026 Q1/Q2 ASCII extracts, via ingestion + preprocessing",
        "=" * 90,
        "",
        "0. SCOPE AND METHOD",
        "-" * 90,
        f"  {COOCCURRENCE_GRAIN}",
        "  Reports are identified by (quarter, PRIMARYID). Each report's drugs are",
        "  de-duplicated on (quarter, PRIMARYID, DRUGNAME_STD) before pairing, so a",
        "  repeated drug name can never form a self-pair.",
        "  Pairs come from an inner self-join on (quarter, PRIMARYID) filtered to",
        "  drug_a < drug_b: one canonical orientation per unordered pair, so A+B and",
        "  B+A are the same pair and no reversed duplicate is counted.",
        "  Q1 and Q2 are mined separately and are never merged into one count.",
        "",
        "  !! " + COOCCURRENCE_DISCLAIMER,
        "",
        "  Measures (per pair, always from report counts):",
        "    support          = reports containing both drugs / total reports",
        "    confidence A->B  = reports containing both drugs / reports containing A",
        "    lift             = observed pair frequency / expected frequency under",
        "                       independence = pair_reports * total / (reports_A * reports_B)",
        "",
        "1. REPORTS, DRUGS AND PAIRS",
        "-" * 90,
        f"  Distinct reports (DEMO, quarter + PRIMARYID) : {results.total_reports:>12,}",
        f"  Reports with at least one drug record       : {results.reports_with_any_drug:>12,}",
        f"  DRUG rows after cleaning                    : {results.drug_rows:>12,}",
        f"  Distinct (report, drug) rows used           : {results.distinct_report_drug_pairs:>12,}",
        f"  Distinct drug names                         : {results.distinct_drug_names:>12,}",
        f"  Co-reported pair rows generated             : {results.pair_rows:>12,}",
        f"  Expected pair rows (sum of C(n,2))          : {results.expected_pairs:>12,}",
        f"  Self-pairs                                  : {results.self_pairs:>12,}",
        f"  Reversed duplicates (drug_a > drug_b)       : {results.reversed_pairs:>12,}",
        f"  Duplicate pair rows                         : {results.duplicate_pair_rows:>12,}",
        f"  Distinct unordered pairs (overall)          : {results.distinct_pairs_overall:>12,}",
        "",
        "  Distinct pairs by quarter (a pair seen in both quarters is counted in each):",
    ]
    for quarter in results.quarters:
        lines.append(
            f"    {quarter}: {results.distinct_pairs_by_quarter.get(quarter, 0):>12,} "
            f"distinct pairs over {results.total_reports_by_quarter.get(quarter, 0):,} reports"
        )

    lines.append("")
    lines.append(f"2. TOP {TOP_PAIRS_REPORT} CO-REPORTED DRUG PAIRS (overall)")
    lines.append("-" * 90)
    header = (
        f"  {'#':>3}  {'DRUG A':<24}{'DRUG B':<24}{'REPORTS':>9}"
        f"{'SUPPORT':>10}{'CONF A->B':>11}{'CONF B->A':>11}{'LIFT':>9}"
    )
    lines.append(header)
    for index, pair in enumerate(results.top_pairs[:TOP_PAIRS_REPORT], start=1):
        lines.append(
            f"  {index:>3}  {_clip(pair.drug_a, 22):<24}{_clip(pair.drug_b, 22):<24}"
            f"{pair.reports:>9,}{pair.support * 100:>9.3f}%{pair.confidence_a_to_b:>11.4f}"
            f"{pair.confidence_b_to_a:>11.4f}{pair.lift:>9.3f}"
        )
    lines.append("  support is shown as a percentage of all reports; lift > 1 means the two")
    lines.append("  drugs were reported together more often than independence would predict -")
    lines.append("  a reporting pattern, not a pharmacological interaction.")

    lines.append("")
    lines.append("3. Q1 vs Q2 COMPARISON (top pairs mined separately per quarter)")
    lines.append("-" * 90)
    for quarter in results.quarters:
        subset = [p for p in results.top_pairs_by_quarter if p.quarter == quarter][
            :TOP_PAIRS_REPORT
        ]
        lines.append(f"  {quarter} - {len(subset)} ranked pair(s) shown")
        for index, pair in enumerate(subset, start=1):
            lines.append(
                f"    {index:>3}  {_clip(pair.drug_a, 22):<24}{_clip(pair.drug_b, 22):<24}"
                f"{pair.reports:>9,}{pair.support * 100:>9.3f}%{pair.confidence_a_to_b:>11.4f}"
                f"{pair.confidence_b_to_a:>11.4f}{pair.lift:>9.3f}"
            )
    if results.shared_top_pairs:
        lines.append("")
        lines.append(
            f"  {len(results.shared_top_pairs)} pair(s) appear in the top "
            f"{TOP_PAIRS_PER_QUARTER} of BOTH quarters:"
        )
        for drug_a, drug_b in results.shared_top_pairs[:20]:
            lines.append(f"    {drug_a} + {drug_b}")
    else:
        lines.append("")
        lines.append("  no pair appears in the top lists of both quarters.")

    lines.append("")
    lines.append("4. FREQUENTLY CO-REPORTED DRUG GROUPS (three-drug combinations)")
    lines.append("-" * 90)
    if results.top_groups:
        lines.append(
            f"  Mined among the {results.group_scope_drugs} most-reported drugs "
            "(frequent-itemset pruning to bound the three-way join)."
        )
        lines.append(f"  {'#':>3}  {'DRUG GROUP':<62}{'REPORTS':>9}{'SUPPORT':>10}")
        for index, group in enumerate(results.top_groups[:TOP_GROUPS_REPORT], start=1):
            label = " + ".join(group.drugs)
            lines.append(
                f"  {index:>3}  {_clip(label, 60):<62}{group.reports:>9,}"
                f"{group.support * 100:>9.3f}%"
            )
        lines.append("")
        for quarter in results.quarters:
            subset = [g for g in results.groups_by_quarter if g.quarter == quarter][
                :TOP_GROUPS_PER_QUARTER
            ]
            lines.append(f"  {quarter} - top {len(subset)} group(s):")
            for index, group in enumerate(subset, start=1):
                label = " + ".join(group.drugs)
                lines.append(
                    f"    {index:>3}  {_clip(label, 60):<62}{group.reports:>9,}"
                    f"{group.support * 100:>9.3f}%"
                )
    else:
        lines.append("  no three-drug groups were mined (max_itemset_size < 3).")

    lines.append("")
    lines.append("5. ASSOCIATION THRESHOLD SCREENING (config.yaml -> analytics.cooccurrence)")
    lines.append("-" * 90)
    lines.append(
        f"  thresholds: support >= {thresholds.get('min_support', 0.0)}  "
        f"confidence >= {thresholds.get('min_confidence', 0.0)}  "
        f"lift >= {thresholds.get('min_lift', 0.0)}"
    )
    lines.append(
        f"  {results.qualifying_pairs:,} of {results.distinct_pairs_overall:,} distinct "
        "pairs satisfy all three thresholds."
    )
    lines.append(
        "  Passing these thresholds only marks pairs worth reviewing: the thresholds"
    )
    lines.append(
        "  are association-rule settings, not a test of interaction or causation."
    )

    lines.append("")
    lines.append("6. VALIDATION CHECKS")
    lines.append("-" * 90)
    for name, ok, detail in results.checks:
        lines.append(f"  [{'PASS' if ok else 'FAIL'}] {name}")
        lines.append(f"         {detail}")

    lines.append("")
    lines.append("7. ISSUES AND ERRORS")
    lines.append("-" * 90)
    if results.errors:
        for error in results.errors:
            lines.append(f"  {error}")
    else:
        lines.append("  none")

    failed = [name for name, ok, _detail in results.checks if not ok]
    lines.append("")
    lines.append("8. SUMMARY")
    lines.append("-" * 90)
    lines.append(
        f"  {len(results.quarters)} quarter(s), {len(results.cleanings)} table(s); "
        f"{results.total_reports:,} reports, {results.distinct_report_drug_pairs:,} "
        f"distinct (report, drug) rows, {results.distinct_pairs_overall:,} distinct "
        f"co-reported pairs, {len(results.top_pairs)} pairs ranked."
    )
    if results.errors or failed:
        lines.append(
            f"  Status: INCOMPLETE - {len(results.errors)} error(s), "
            f"{len(failed)} failed check(s)."
        )
    else:
        lines.append("  Status: COMPLETE - all aggregations produced and all checks passed.")
    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Driver
# ---------------------------------------------------------------------------
def run(
    spark: Any,
    *,
    quarters: Sequence[str],
    settings: Mapping[str, Any],
    quarter_dirs: Mapping[str, Path],
    output_dir: Optional[Path] = None,
) -> CooccurrenceResults:
    """Analyse, persist the outputs (when a directory is given) and return results."""
    log = get_logger(__name__)
    results = analyze(
        spark, quarters=quarters, settings=settings, quarter_dirs=quarter_dirs
    )
    if output_dir is not None:
        written = write_outputs(results, output_dir=output_dir)
        for name, path in written.items():
            log.info("wrote %s -> %s", name, path)
    return results


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Drug co-occurrence over the real FAERS extracts (read-only; no Parquet)."
    )
    parser.add_argument("--quarters", nargs="*", default=None, help="e.g. 2026_Q1 2026_Q2")
    parser.add_argument(
        "--report",
        default=None,
        help="Report path (default reports/drug_cooccurrence_report.txt; '' disables it).",
    )
    parser.add_argument(
        "--outputs",
        default=None,
        help="Result directory (default data/analytics/drug_cooccurrence; '' disables it).",
    )
    args = parser.parse_args(argv)

    log = get_logger(__name__)
    settings = load_settings()

    all_quarters = [quarter for quarter, _dir in get_quarter_dirs()]
    quarters = list(args.quarters or all_quarters)
    unknown = [q for q in quarters if q not in all_quarters]
    if unknown:
        log.error("Unknown quarter(s): %s", ", ".join(unknown))
        return 1

    quarter_dirs = dict(get_quarter_dirs())
    if args.outputs is None:
        output_dir: Optional[Path] = get_path("analytics") / "drug_cooccurrence"
    else:
        output_dir = Path(args.outputs) if args.outputs else None

    try:
        spark = create_spark_session(app_name="DrugSafetyCooccurrence")
    except SparkEnvironmentError as exc:
        log.error("%s", exc)
        return 1

    try:
        results = run(
            spark,
            quarters=quarters,
            settings=settings,
            quarter_dirs=quarter_dirs,
            output_dir=output_dir,
        )
    except (CooccurrenceError, CleaningError, IngestionError) as exc:
        log.error("Co-occurrence analysis failed: %s", exc)
        return 2
    finally:
        stop_spark_session(spark)

    report = render_report(results)
    print(report)

    report_path = args.report
    if report_path is None:
        report_path = str(get_path("reports") / "drug_cooccurrence_report.txt")
    if report_path:
        target = Path(report_path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(report + "\n", encoding="utf-8")
        log.info("Report written to: %s", target)

    if results.errors or any(not ok for _n, ok, _d in results.checks):
        return 2
    return 0


if __name__ == "__main__":  # pragma: no cover - manual entry point
    raise SystemExit(main())
