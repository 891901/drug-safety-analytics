#: Tables this module needs (a subset of the seven FAERS tables).
COOCCURRENCE_TABLES: Tuple[str, ...] = ("DEMO", "DRUG")

#: The standardised drug-name column produced by the preprocessing module.
DRUG_NAME_COLUMN = "DRUGNAME_STD"

#: Grain statement reused in the report.
COOCCURRENCE_GRAIN = (
    "Report = one distinct (quarter, PRIMARYID). Drug pair = one unordered "
    "pair {drug_a, drug_b} with drug_a < drug_b, counted once per report."
)

#: Mandatory caution; echoed in the report and the JSON summary.
COOCCURRENCE_DISCLAIMER = (
    "Co-occurrence only means the two drugs were reported together in the same "
    "FAERS report. It is NOT evidence of a drug-drug interaction, of a shared "
    "adverse event, of an underlying indication, or of causation."
)

# --- output sizing ---------------------------------------------------------
TOP_PAIRS_CSV = 500
TOP_PAIRS_REPORT = 20
TOP_PAIRS_PER_QUARTER = 20
TOP_GROUPS_CSV = 200
TOP_GROUPS_REPORT = 20
TOP_GROUPS_PER_QUARTER = 10

#: Three-drug groups are mined only among the most-reported drugs, to bound the
#: cost of the three-way self-join. This is the usual frequent-itemset pruning:
#: a frequent triple can only be built from frequently reported drugs.
GROUP_DRUG_LIMIT = 100


class CooccurrenceError(RuntimeError):
    """Raised when the co-occurrence aggregation cannot be produced."""


# ---------------------------------------------------------------------------
# Result containers
# ---------------------------------------------------------------------------
@dataclass
class PairMetric:
    """One drug pair with its observed counts and the three association measures.

    Every measure is derived from integer report counts, so it can be
    recomputed exactly and verified independently of Spark's floating point.
    """

    drug_a: str
    drug_b: str
    reports: int
    reports_a: int
    reports_b: int
    total_reports: int
    quarter: Optional[str] = None
    passes_thresholds: bool = False

    @property
    def support(self) -> float:
        """Reports containing both drugs / total reports."""
        return self.reports / self.total_reports if self.total_reports else 0.0

    @property
    def confidence_a_to_b(self) -> float:
        """Reports containing both drugs / reports containing ``drug_a``."""
        return self.reports / self.reports_a if self.reports_a else 0.0

    @property
    def confidence_b_to_a(self) -> float:
        """Reports containing both drugs / reports containing ``drug_b``."""
        return self.reports / self.reports_b if self.reports_b else 0.0

    @property
    def lift(self) -> float:
        """Observed pair frequency / expected pair frequency under independence."""
        if not (self.reports_a and self.reports_b and self.total_reports):
            return 0.0
        return (self.reports * self.total_reports) / (self.reports_a * self.reports_b)


@dataclass
class GroupMetric:
    """One co-reported drug group (a three-drug combination)."""

    drugs: Tuple[str, str, str]
    reports: int
    total_reports: int
    quarter: Optional[str] = None

    @property
    def support(self) -> float:
        return self.reports / self.total_reports if self.total_reports else 0.0


@dataclass
class CooccurrenceResults:
    """Every artefact produced by one co-occurrence run."""

    quarters: List[str] = field(default_factory=list)
    cleanings: Dict[str, TableCleaning] = field(default_factory=dict)
    thresholds: Dict[str, float] = field(default_factory=dict)

    # section 1 - report / drug / pair counts
    total_reports: int = 0
    total_reports_by_quarter: Dict[str, int] = field(default_factory=dict)
    reports_with_any_drug: int = 0
    drug_rows: int = 0
    distinct_report_drug_pairs: int = 0
    distinct_drug_names: int = 0
    pair_rows: int = 0
    expected_pairs: int = 0
    self_pairs: int = 0
    reversed_pairs: int = 0
    duplicate_pair_rows: int = 0
    distinct_pairs_overall: int = 0
    distinct_pairs_by_quarter: Dict[str, int] = field(default_factory=dict)
    group_scope_drugs: int = 0

    # section 2 - pair metrics
    top_pairs: List[PairMetric] = field(default_factory=list)
    top_pairs_by_quarter: List[PairMetric] = field(default_factory=list)
    metric_max_abs_diff: float = 0.0

    # section 3 - Q1 vs Q2
    shared_top_pairs: List[Tuple[str, str]] = field(default_factory=list)

    # section 4 - co-reported groups
    top_groups: List[GroupMetric] = field(default_factory=list)
    groups_by_quarter: List[GroupMetric] = field(default_factory=list)

    # section 5 - threshold screening
    qualifying_pairs: int = 0

    # validation
    checks: List[Tuple[str, bool, str]] = field(default_factory=list)
    errors: List[str] = field(default_factory=list)

    def as_summary(self, generated_at: str) -> Dict[str, Any]:
        return {
            "generated_at": generated_at,
            "quarters": self.quarters,
            "disclaimer": COOCCURRENCE_DISCLAIMER,
            "grain": COOCCURRENCE_GRAIN,
            "thresholds": self.thresholds,
            "counts": {
                "total_reports": self.total_reports,
                "reports_with_at_least_one_drug": self.reports_with_any_drug,
                "drug_rows": self.drug_rows,
                "distinct_report_drug_pairs": self.distinct_report_drug_pairs,
                "distinct_drug_names": self.distinct_drug_names,
                "drug_pair_rows": self.pair_rows,
                "expected_pair_rows": self.expected_pairs,
                "self_pairs": self.self_pairs,
                "reversed_pairs": self.reversed_pairs,
                "duplicate_pair_rows": self.duplicate_pair_rows,
                "distinct_pairs_overall": self.distinct_pairs_overall,
                "qualifying_pairs": self.qualifying_pairs,
            },
            "total_reports_by_quarter": self.total_reports_by_quarter,
            "distinct_pairs_by_quarter": self.distinct_pairs_by_quarter,
            "top_20_pairs": [self._pair_dict(pair) for pair in self.top_pairs[:TOP_PAIRS_REPORT]],
            "top_groups": [
                {"drugs": list(group.drugs), "reports": group.reports, "support": group.support}
                for group in self.top_groups[:TOP_GROUPS_REPORT]
            ],
            "checks": [
                {"name": name, "passed": ok, "detail": detail}
                for name, ok, detail in self.checks
            ],
            "errors": self.errors,
        }

    @staticmethod
    def _pair_dict(pair: PairMetric) -> Dict[str, Any]:
        return {
            "drug_a": pair.drug_a,
            "drug_b": pair.drug_b,
            "reports": pair.reports,
            "reports_a": pair.reports_a,
            "reports_b": pair.reports_b,
            "support": pair.support,
            "confidence_a_to_b": pair.confidence_a_to_b,
            "confidence_b_to_a": pair.confidence_b_to_a,
            "lift": pair.lift,
            "passes_thresholds": pair.passes_thresholds,
        }


# ---------------------------------------------------------------------------
# Small helpers
# ---------------------------------------------------------------------------
def _count_rows() -> "F.Column":
    """A portable row counter."""
    return F.count(F.lit(1))


def _clip(text: str, width: int) -> str:
    """Truncate ``text`` to ``width`` characters, adding an ellipsis when cut."""
    return text if len(text) <= width else text[: width - 1] + "\u2026"


def _clean_inputs(
    spark: Any,
    *,
    quarters: Sequence[str],
    settings: Mapping[str, Any],
    quarter_dirs: Mapping[str, Path],
) -> Tuple[Dict[str, DataFrame], Dict[str, TableCleaning], List[str]]:
    """Read + clean the DEMO and DRUG tables via the preprocessing module."""
    log = get_logger(__name__)
    frames: Dict[str, DataFrame] = {}
    cleanings: Dict[str, TableCleaning] = {}
    errors: List[str] = []

    for table in COOCCURRENCE_TABLES:
        try:
            frame, cleaning = clean_table(spark, table, quarters, settings, quarter_dirs)
        except (CleaningError, IngestionError) as exc:
            log.error("%s: cleaning failed: %s", table, exc)
            errors.append(f"[{table}] {exc}")
            continue
        except Exception as exc:  # noqa: BLE001 - one bad table must not abort the run
            log.error("%s: unexpected failure: %s", table, exc)
            errors.append(f"[{table}] {type(exc).__name__}: {exc}")
            continue
        frames[table] = frame
        cleanings[table] = cleaning
        log.info("%s: %s rows cleaned", table, f"{cleaning.rows_after:,}")
    return frames, cleanings, errors


def _order_pairs(frame: DataFrame, columns: Sequence[str]) -> DataFrame:
    """Deterministic ordering: most reports first, then alphabetical drug names."""
    return frame.orderBy(
        F.desc("reports"), *[F.asc(name) for name in columns]
    )


# ---------------------------------------------------------------------------
# Analysis
# ---------------------------------------------------------------------------
def analyze(
    spark: Any,
    *,
    quarters: Sequence[str],
    settings: Mapping[str, Any],
    quarter_dirs: Mapping[str, Path],
) -> CooccurrenceResults:
    """Mine every co-reported drug pair and return the collected results."""
    log = get_logger(__name__)
    results = CooccurrenceResults(quarters=list(quarters))

    thresholds = get_analytics_config("cooccurrence")
    min_support = float(thresholds.get("min_support", 0.0) or 0.0)
    min_confidence = float(thresholds.get("min_confidence", 0.0) or 0.0)
    min_lift = float(thresholds.get("min_lift", 0.0) or 0.0)
    max_itemset = int(thresholds.get("max_itemset_size", 2) or 2)
    results.thresholds = {
        "min_support": min_support,
        "min_confidence": min_confidence,
        "min_lift": min_lift,
        "max_itemset_size": max_itemset,
        "group_drug_limit": GROUP_DRUG_LIMIT,
    }

    frames, cleanings, errors = _clean_inputs(
        spark, quarters=quarters, settings=settings, quarter_dirs=quarter_dirs
    )
    results.cleanings = cleanings
    results.errors.extend(errors)

    missing = [table for table in COOCCURRENCE_TABLES if table not in frames]
    if missing:
        raise CooccurrenceError(
            "required table(s) unavailable: " + ", ".join(missing) + "; see errors"
        )

    quarter = QUARTER_COLUMN
    reports = frames["DEMO"].select(quarter, "PRIMARYID").persist()
    # Report x drug incidence matrix: one row per distinct drug per report, which
    # is exactly the "remove duplicate drug names within a report" requirement.
    drugs = (
        frames["DRUG"]
        .select(quarter, "PRIMARYID", DRUG_NAME_COLUMN)
        .filter(F.col(DRUG_NAME_COLUMN).isNotNull())
        .distinct()
        .persist()
    )

    try:
        # ---- 1. report / drug / pair counts --------------------------------
        results.drug_rows = cleanings["DRUG"].rows_after
        results.total_reports = reports.select("PRIMARYID").distinct().count()
        results.total_reports_by_quarter = {
            row[quarter]: int(row["reports"])
            for row in reports.groupBy(quarter).agg(_count_rows().alias("reports")).collect()
        }
        results.distinct_report_drug_pairs = drugs.count()
        results.distinct_drug_names = drugs.select(DRUG_NAME_COLUMN).distinct().count()
        results.reports_with_any_drug = drugs.select("PRIMARYID").distinct().count()

        # ---- 2. every co-reported pair, canonically ordered ----------------
        left = drugs.select(
            F.col(quarter).alias(quarter),
            F.col("PRIMARYID").alias("PRIMARYID"),
            F.col(DRUG_NAME_COLUMN).alias("drug_a"),
        )
        right = drugs.select(
            F.col(quarter).alias(quarter),
            F.col("PRIMARYID").alias("PRIMARYID"),
            F.col(DRUG_NAME_COLUMN).alias("drug_b"),
        )
        # Equi-join on the report key only - not a Cartesian product - and the
        # strict ordering keeps exactly one orientation of each unordered pair.
        pair_rows = (
            left.join(right, on=[quarter, "PRIMARYID"])
            .filter(F.col("drug_a") < F.col("drug_b"))
            .persist()
        )

        results.pair_rows = pair_rows.count()
        violations = pair_rows.agg(
            F.coalesce(
                F.sum(F.when(F.col("drug_a") == F.col("drug_b"), F.lit(1)).otherwise(F.lit(0))),
                F.lit(0),
            ).alias("self_pairs"),
            F.coalesce(
                F.sum(F.when(F.col("drug_a") > F.col("drug_b"), F.lit(1)).otherwise(F.lit(0))),
                F.lit(0),
            ).alias("reversed_pairs"),
        ).first()
        results.self_pairs = int(violations["self_pairs"])
        results.reversed_pairs = int(violations["reversed_pairs"])
        results.duplicate_pair_rows = results.pair_rows - pair_rows.distinct().count()

        # Independent expectation: sum over reports of C(drugs_in_report, 2).
        per_report = drugs.groupBy(quarter, "PRIMARYID").agg(
            _count_rows().alias("drug_count")
        )
        expected = per_report.agg(
            F.coalesce(
                F.sum(
                    F.col("drug_count") * (F.col("drug_count") - F.lit(1)) / F.lit(2)
                ),
                F.lit(0),
            ).alias("expected")
        ).first()
        results.expected_pairs = int(expected["expected"] or 0)
        log.info(
            "reports=%s  report-drug rows=%s  co-reported pair rows=%s",
            f"{results.total_reports:,}",
            f"{results.distinct_report_drug_pairs:,}",
            f"{results.pair_rows:,}",
        )

        # ---- pair counts: overall and per quarter --------------------------
        overall_counts = (
            pair_rows.groupBy("drug_a", "drug_b").agg(_count_rows().alias("reports")).persist()
        )
        quarter_counts = (
            pair_rows.groupBy(quarter, "drug_a", "drug_b")
            .agg(_count_rows().alias("reports"))
            .persist()
        )
        results.distinct_pairs_overall = overall_counts.count()
        quarter_pair_totals = quarter_counts.groupBy(quarter).agg(
            _count_rows().alias("pairs")
        )
        results.distinct_pairs_by_quarter = {
            row[quarter]: int(row["pairs"]) for row in quarter_pair_totals.collect()
        }
        pair_rows.unpersist()

        # ---- drug report counts (needed for confidence and lift) ------------
        drug_counts = drugs.groupBy(DRUG_NAME_COLUMN).agg(_count_rows().alias("reports"))
        quarter_drug_counts = drugs.groupBy(quarter, DRUG_NAME_COLUMN).agg(
            _count_rows().alias("reports")
        )
        quarter_totals = reports.groupBy(quarter).agg(
            F.countDistinct("PRIMARYID").alias("quarter_total")
        )

        # ---- 3/4. top pairs with support, confidence and lift ---------------
        def _add_metrics(counts: DataFrame, *, per_quarter: bool) -> DataFrame:
            """Broadcast-join the per-drug report counts and derive the measures."""
            if per_quarter:
                count_a = quarter_drug_counts.select(
                    F.col(quarter).alias(quarter),
                    F.col(DRUG_NAME_COLUMN).alias("drug_a"),
                    F.col("reports").alias("reports_a"),
                )
                count_b = quarter_drug_counts.select(
                    F.col(quarter).alias(quarter),
                    F.col(DRUG_NAME_COLUMN).alias("drug_b"),
                    F.col("reports").alias("reports_b"),
                )
                keys_a, keys_b = [quarter, "drug_a"], [quarter, "drug_b"]
                frame = counts.join(F.broadcast(count_a), on=keys_a, how="inner")
                frame = frame.join(F.broadcast(count_b), on=keys_b, how="inner")
                frame = frame.join(F.broadcast(quarter_totals), on=quarter, how="inner")
                denominator = F.col("quarter_total")
            else:
                count_a = drug_counts.select(
                    F.col(DRUG_NAME_COLUMN).alias("drug_a"),
                    F.col("reports").alias("reports_a"),
                )
                count_b = drug_counts.select(
                    F.col(DRUG_NAME_COLUMN).alias("drug_b"),
                    F.col("reports").alias("reports_b"),
                )
                frame = counts.join(F.broadcast(count_a), on="drug_a", how="inner")
                frame = frame.join(F.broadcast(count_b), on="drug_b", how="inner")
                denominator = F.lit(results.total_reports)
            return (
                frame.withColumn("support", F.col("reports") / denominator)
                .withColumn("confidence_a_to_b", F.col("reports") / F.col("reports_a"))
                .withColumn("confidence_b_to_a", F.col("reports") / F.col("reports_b"))
                .withColumn(
                    "lift",
                    F.col("reports") * denominator / (F.col("reports_a") * F.col("reports_b")),
                )
            )

        enriched_overall = _add_metrics(overall_counts, per_quarter=False)

        threshold_expr = (
            (F.col("support") >= F.lit(min_support))
            & (F.col("confidence_a_to_b") >= F.lit(min_confidence))
            & (F.col("confidence_b_to_a") >= F.lit(min_confidence))
            & (F.col("lift") >= F.lit(min_lift))
        )
        qualifying = enriched_overall.agg(
            F.coalesce(
                F.sum(F.when(threshold_expr, F.lit(1)).otherwise(F.lit(0))), F.lit(0)
            ).alias("qualifying")
        ).first()
        results.qualifying_pairs = int(qualifying["qualifying"])

        top_rows = _order_pairs(enriched_overall, ["drug_a", "drug_b"]).limit(TOP_PAIRS_CSV).collect()
        for row in top_rows:
            metric = PairMetric(
                drug_a=row["drug_a"],
                drug_b=row["drug_b"],
                reports=int(row["reports"]),
                reports_a=int(row["reports_a"]),
                reports_b=int(row["reports_b"]),
                total_reports=results.total_reports,
                passes_thresholds=bool(
                    row["support"] >= min_support
                    and row["confidence_a_to_b"] >= min_confidence
                    and row["confidence_b_to_a"] >= min_confidence
                    and row["lift"] >= min_lift
                ),
            )
            # Cross-check the Spark-computed measures against the exact
            # recomputation from integer counts.
            results.metric_max_abs_diff = max(
                results.metric_max_abs_diff,
                abs(float(row["support"]) - metric.support),
                abs(float(row["confidence_a_to_b"]) - metric.confidence_a_to_b),
                abs(float(row["confidence_b_to_a"]) - metric.confidence_b_to_a),
                abs(float(row["lift"]) - metric.lift),
            )
            results.top_pairs.append(metric)

        # ---- 5. Q1 vs Q2 ----------------------------------------------------
        rank_quarter = Window.partitionBy(quarter).orderBy(
            F.desc("reports"), F.asc("drug_a"), F.asc("drug_b")
        )
        quarter_top_counts = (
            quarter_counts.withColumn("rank", F.row_number().over(rank_quarter))
            .filter(F.col("rank") <= F.lit(TOP_PAIRS_PER_QUARTER))
            .drop("rank")
        )
        quarter_top = _add_metrics(quarter_top_counts, per_quarter=True).collect()
        for row in sorted(
            quarter_top,
            key=lambda item: (item[quarter], -int(item["reports"]), item["drug_a"], item["drug_b"]),
        ):
            metric = PairMetric(
                drug_a=row["drug_a"],
                drug_b=row["drug_b"],
                reports=int(row["reports"]),
                reports_a=int(row["reports_a"]),
                reports_b=int(row["reports_b"]),
                total_reports=int(row["quarter_total"]),
                quarter=row[quarter],
            )
            results.metric_max_abs_diff = max(
                results.metric_max_abs_diff,
                abs(float(row["support"]) - metric.support),
                abs(float(row["confidence_a_to_b"]) - metric.confidence_a_to_b),
                abs(float(row["lift"]) - metric.lift),
            )
            results.top_pairs_by_quarter.append(metric)

        top_by_quarter: Dict[str, set] = {}
        for metric in results.top_pairs_by_quarter:
            top_by_quarter.setdefault(metric.quarter or "", set()).add(
                (metric.drug_a, metric.drug_b)
            )
        if len(top_by_quarter) >= 2:
            shared: set = set()
            quarter_sets = list(top_by_quarter.values())
            for pair in quarter_sets[0]:
                if all(pair in other for other in quarter_sets[1:]):
                    shared.add(pair)
            results.shared_top_pairs = sorted(shared)

        # Both pair-count frames have been fully consumed by the sections above.
        overall_counts.unpersist()
        quarter_counts.unpersist()

        # ---- 6. frequently co-reported drug groups (three-drug combinations) -
        if max_itemset >= 3:
            frequent_names = [
                name
                for name, _count in sorted(
                    (
                        (row[DRUG_NAME_COLUMN], int(row["reports"]))
                        for row in drug_counts.collect()
                    ),
                    key=lambda item: (-item[1], item[0]),
                )[:GROUP_DRUG_LIMIT]
            ]
            results.group_scope_drugs = len(frequent_names)
            frequent = drugs.filter(F.col(DRUG_NAME_COLUMN).isin(frequent_names))
            first = frequent.select(
                F.col(quarter).alias(quarter),
                F.col("PRIMARYID").alias("PRIMARYID"),
                F.col(DRUG_NAME_COLUMN).alias("drug_a"),
            )
            second = frequent.select(
                F.col(quarter).alias(quarter),
                F.col("PRIMARYID").alias("PRIMARYID"),
                F.col(DRUG_NAME_COLUMN).alias("drug_b"),
            )
            third = frequent.select(
                F.col(quarter).alias(quarter),
                F.col("PRIMARYID").alias("PRIMARYID"),
                F.col(DRUG_NAME_COLUMN).alias("drug_c"),
            )
            pairs_two = first.join(second, on=[quarter, "PRIMARYID"]).filter(
                F.col("drug_a") < F.col("drug_b")
            )
            triples = pairs_two.join(third, on=[quarter, "PRIMARYID"]).filter(
                F.col("drug_c") > F.col("drug_b")
            )
            quarter_groups = (
                triples.groupBy(quarter, "drug_a", "drug_b", "drug_c")
                .agg(_count_rows().alias("reports"))
                .persist()
            )
            group_totals = {
                row[quarter]: int(row["quarter_total"]) for row in quarter_totals.collect()
            }
            results.top_groups = [
                GroupMetric(
                    drugs=(row["drug_a"], row["drug_b"], row["drug_c"]),
                    reports=int(row["reports"]),
                    total_reports=results.total_reports,
                )
                for row in _order_pairs(
                    quarter_groups.groupBy("drug_a", "drug_b", "drug_c").agg(
                        F.sum("reports").alias("reports")
                    ),
                    ["drug_a", "drug_b", "drug_c"],
                )
                .limit(TOP_GROUPS_CSV)
                .collect()
            ]
            rank_group = Window.partitionBy(quarter).orderBy(
                F.desc("reports"), F.asc("drug_a"), F.asc("drug_b"), F.asc("drug_c")
            )
            group_rows = (
                quarter_groups.withColumn("rank", F.row_number().over(rank_group))
                .filter(F.col("rank") <= F.lit(TOP_GROUPS_PER_QUARTER))
                .collect()
            )
            results.groups_by_quarter = [
                GroupMetric(
                    drugs=(row["drug_a"], row["drug_b"], row["drug_c"]),
                    reports=int(row["reports"]),
                    total_reports=group_totals.get(row[quarter], results.total_reports),
                    quarter=row[quarter],
                )
                for row in sorted(
                    group_rows,
                    key=lambda item: (
                        item[quarter],
                        -int(item["reports"]),
                        item["drug_a"],
                        item["drug_b"],
                        item["drug_c"],
                    ),
                )
            ]
            quarter_groups.unpersist()
    finally:
        for frame in (reports, drugs):
            frame.unpersist()

    results.checks = _validate(results)
    return results


def _validate(results: CooccurrenceResults) -> List[Tuple[str, bool, str]]:
    """Cross-check the aggregates; every check is recorded pass or fail."""
    checks: List[Tuple[str, bool, str]] = []

    cleaning_ok = all(
        item.rows_before == item.rows_after and not item.errors
        for item in results.cleanings.values()
    )
    checks.append(
        (
            "cleaning removed no rows (DEMO/DRUG)",
            cleaning_ok,
            "; ".join(
                f"{table}={item.rows_before:,}->{item.rows_after:,}"
                for table, item in results.cleanings.items()
            ),
        )
    )

    checks.append(
        (
            "duplicate drug names within a report removed before pairing",
            results.distinct_report_drug_pairs < results.drug_rows
            and results.distinct_report_drug_pairs > 0,
            f"{results.drug_rows:,} DRUG rows reduced to "
            f"{results.distinct_report_drug_pairs:,} distinct "
            f"(quarter, PRIMARYID, drug) rows",
        )
    )

    checks.append(
        (
            "no self-pairs (a drug is never paired with itself)",
            results.self_pairs == 0,
            f"{results.self_pairs} self-pair row(s)",
        )
    )
    checks.append(
        (
            "no reversed duplicate pairs (drug_a < drug_b always)",
            results.reversed_pairs == 0,
            f"{results.reversed_pairs} row(s) with drug_a > drug_b",
        )
    )
    checks.append(
        (
            "no duplicate pair rows (one unordered pair per report)",
            results.duplicate_pair_rows == 0,
            f"{results.pair_rows:,} rows, {results.pair_rows - results.duplicate_pair_rows:,} distinct",
        )
    )
    checks.append(
        (
            "pair count equals the sum of C(drugs in report, 2) over all reports",
            results.pair_rows == results.expected_pairs,
            f"{results.pair_rows:,} pair rows vs {results.expected_pairs:,} expected",
        )
    )

    quarter_total = sum(results.distinct_pairs_by_quarter.values())
    checks.append(
        (
            "distinct pairs per quarter sum to the per-quarter pair counts",
            quarter_total >= results.distinct_pairs_overall > 0,
            " + ".join(f"{q}={n:,}" for q, n in sorted(results.distinct_pairs_by_quarter.items()))
            + f" = {quarter_total:,} (overall distinct pairs {results.distinct_pairs_overall:,}; "
            "pairs shared by both quarters are counted once per quarter)",
        )
    )
    checks.append(
        (
            "Q1 and Q2 are both present and distinguishable",
            set(results.distinct_pairs_by_quarter) == set(results.quarters)
            and len(set(results.distinct_pairs_by_quarter.values())) >= 1,
            ", ".join(
                f"{q}={n:,}" for q, n in sorted(results.distinct_pairs_by_quarter.items())
            ),
        )
    )

    if results.top_pairs:
        bounded = all(
            pair.reports <= pair.reports_a
            and pair.reports <= pair.reports_b
            and pair.reports <= pair.total_reports
            for pair in results.top_pairs
        )
        checks.append(
            (
                "a pair is never reported more often than either of its drugs",
                bounded,
                f"checked {len(results.top_pairs)} ranked pair(s)",
            )
        )
        ordered = all(
            results.top_pairs[index].reports >= results.top_pairs[index + 1].reports
            for index in range(len(results.top_pairs) - 1)
        )
        checks.append(
            (
                "ranked pair counts are positive and non-increasing",
                ordered and all(pair.reports > 0 for pair in results.top_pairs),
                f"{len(results.top_pairs)} pair(s) ranked",
            )
        )
    else:
        checks.append(("a pair is never reported more often than either of its drugs", False, "no pairs"))
        checks.append(("ranked pair counts are positive and non-increasing", False, "no pairs"))

    checks.append(
        (
            "support, confidence and lift recomputed exactly from integer counts",
            results.metric_max_abs_diff <= 1e-9,
            f"max |Spark - exact| difference = {results.metric_max_abs_diff:.3e} "
            f"over {len(results.top_pairs) + len(results.top_pairs_by_quarter)} row(s)",
        )
    )
    checks.append(
        (
            "threshold screening is within the observed pair universe",
            0 <= results.qualifying_pairs <= results.distinct_pairs_overall,
            f"{results.qualifying_pairs:,} qualifying pair(s) of "
            f"{results.distinct_pairs_overall:,} distinct pair(s)",
        )
    )

    if results.top_groups:
        bounded_groups = all(
            group.reports <= group.total_reports and group.reports > 0
            for group in results.top_groups
        )
        checks.append(
            (
                "co-reported group counts are positive and within total reports",
                bounded_groups,
                f"checked {len(results.top_groups)} group(s) mined from the "
                f"{results.group_scope_drugs} most-reported drugs",
            )
        )
    else:
        checks.append(
            (
                "co-reported group counts are positive and within total reports",
                False,
                "no groups mined",
            )
        )
    return checks


