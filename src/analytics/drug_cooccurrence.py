def _write_csv(path: Path, header: Sequence[str], rows: Sequence[Sequence[Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(header)
        writer.writerows(rows)


def write_outputs(
    results: CooccurrenceResults,
    *,
    output_dir: Path,
    generated_at: Optional[datetime] = None,
) -> Dict[str, Path]:
    """Persist the pair table, the per-quarter table and the groups; return paths."""
    timestamp = (generated_at or datetime.now()).isoformat(timespec="seconds")
    output_dir.mkdir(parents=True, exist_ok=True)
    written: Dict[str, Path] = {}

    def emit(name: str, header: Sequence[str], rows: Sequence[Sequence[Any]]) -> None:
        target = output_dir / name
        _write_csv(target, header, rows)
        written[name] = target

    pair_header = [
        "drug_a",
        "drug_b",
        "reports",
        "support",
        "confidence_a_to_b",
        "confidence_b_to_a",
        "lift",
        "reports_a",
        "reports_b",
        "passes_thresholds",
    ]

    def pair_row(pair: PairMetric, *, with_quarter: bool) -> List[Any]:
        row: List[Any] = [pair.quarter] if with_quarter else []
        row += [
            pair.drug_a,
            pair.drug_b,
            pair.reports,
            round(pair.support, 10),
            round(pair.confidence_a_to_b, 10),
            round(pair.confidence_b_to_a, 10),
            round(pair.lift, 10),
            pair.reports_a,
            pair.reports_b,
            pair.passes_thresholds,
        ]
        return row

    emit(
        "cooccurrence_top_pairs.csv",
        pair_header,
        [pair_row(pair, with_quarter=False) for pair in results.top_pairs],
    )
    emit(
        "cooccurrence_pairs_by_quarter.csv",
        ["quarter", *pair_header],
        [pair_row(pair, with_quarter=True) for pair in results.top_pairs_by_quarter],
    )
    emit(
        "cooccurrence_top_groups.csv",
        ["drug_a", "drug_b", "drug_c", "reports", "support"],
        [
            [*group.drugs, group.reports, round(group.support, 10)]
            for group in results.top_groups
        ],
    )

    summary_path = output_dir / "cooccurrence_summary.json"
    summary_path.write_text(
        json.dumps(results.as_summary(timestamp), indent=2) + "\n", encoding="utf-8"
    )
    written["cooccurrence_summary.json"] = summary_path
    return written


